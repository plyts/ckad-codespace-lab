def front(text):
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.S)
    if not m:
        return {}, text
    meta = dict(l.split(":", 1) for l in m.group(1).splitlines() if ":" in l)
    return {k.strip(): v.strip() for k, v in meta.items()}, m.group(2)


TERM_RULES = [
    (r"\b(PASS|Running|Ready|Bound|Completed|Complete|yes|deployed|successfully rolled out|condition met|Labo conforme\.?)\b", "ok"),
    (r"\b(Pending|WARN|ContainerCreating|Terminating|SKIP|superseded)\b", "warn"),
    (r"\b(FAIL|Error|CrashLoopBackOff|ImagePullBackOff|ErrImagePull|OOMKilled|CreateContainerConfigError|"
     r"FailedScheduling|FailedMount|Forbidden|Invalid|refused|timed out|no|BackOff|Failed)\b", "err"),
]


def colorize(txt):
    out = []
    for line in txt.split("\n"):
        if line.startswith("$ "):
            out.append(f'<span class="prompt">$</span> <span class="cmd">{line[2:]}</span>')
            continue
        for rx, cls in TERM_RULES:
            line = re.sub(rx, lambda m, c=cls: f'<span class="t-{c}">{m.group(0)}</span>', line)
        out.append(line)
    return "\n".join(out)


def capture_block(name, lang):
    s = S[lang]
    f = CAPS / f"{name}.txt"
    if not f.exists():
        return f'\n<div class="callout missing"><b>{s["missing"]}</b> : <code>{name}</code> — {s["missing_hint"]}.</div>\n'
    mf = CAPS / ("journal.meta" if name.startswith("err-") else "guide.meta")
    meta = mf.read_text().strip() if mf.exists() else "?"
    if lang == "en":
        meta = meta.replace("capturé le", "captured on").replace(" sur ", " on ").replace("contexte", "context")
    body = colorize(html.escape(f.read_text().rstrip()))
    return (f'\n<figure class="term"><pre class="terminal"><code>{body}</code></pre>'
            f'<figcaption>{s["real"]} · {html.escape(meta)}</figcaption></figure>\n')


def unit_text(u, lang):
    """Titre et consigne d'une unité dans la langue voulue (task.en.md si présent)."""
    if lang == "en":
        f = u.path / "task.en.md"
        if f.exists():
            meta, body = front(f.read_text(encoding="utf-8"))
            return meta.get("title", u.title), body.strip()
    return u.title, u.body


def exercise_list(domain, lang):
    rows = [S[lang]["ex_table"], "|---|---|---|---|"]
    for u in EX.all_units():
        if u.kind == "exercise" and u.domain == domain:
            rows.append(f"| `{u.id}` | {u.level} | {u.time} min | {unit_text(u, lang)[0]} |")
    return "\n".join(rows) + "\n\n" + S[lang]["ex_hint"]


def preprocess(md, lang):
    md = re.sub(r"\{\{capture:([a-z0-9-]+)\}\}", lambda m: capture_block(m.group(1), lang), md)
    md = re.sub(r"\{\{exercices:(\d)\}\}", lambda m: exercise_list(m.group(1), lang), md)

    def callout(m):
        kind, title, body = m.group(1), (m.group(2) or "").strip(), m.group(3)
        label = S[lang]["callout"][kind] + (f" — {title}" if title else "")
        return f'\n<div class="callout {kind}" markdown="1">\n<p class="callout-title">{label}</p>\n\n{body}\n</div>\n'
    return re.sub(r"^:::(piege|pourquoi|verif|examen)[ \t]*(.*?)\n(.*?)\n:::[ \t]*$", callout, md, flags=re.M | re.S)


