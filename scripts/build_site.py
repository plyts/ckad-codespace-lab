def page_source(name, lang):
    """(texte, traduit ?) pour une page de docs."""
    if name == "mode-emploi":
        f = ROOT / ("MODE-EMPLOI.en.md" if lang == "en" else "MODE-EMPLOI.md")
        if f.exists():
            return f.read_text(encoding="utf-8"), True
        return (ROOT / "MODE-EMPLOI.md").read_text(encoding="utf-8"), lang == "fr"
    f = (DOCS / "en" / f"{name}.md") if lang == "en" else (DOCS / f"{name}.md")
    if f.exists():
        return f.read_text(encoding="utf-8"), True
    fr = DOCS / f"{name}.md"
    return (fr.read_text(encoding="utf-8"), False) if fr.exists() else (None, False)


def render(name, text, lang, color_default, k8s, nav_items, out_dir, translated=True, extra=""):
    s = S[lang]
    meta, body = front(text)
    if name == "mode-emploi":
        meta = {"title": "Mode d'emploi" if lang == "fr" else "User guide", "color": "gris"}
    body = body.replace("{{scenarios}}", gen_scenarios(lang))
    md = markdown.Markdown(extensions=["fenced_code", "tables", "toc", "attr_list", "md_in_html", "sane_lists"],
                           extension_configs={"toc": {"permalink": "#", "toc_depth": "2-3"}})
    content = md.convert(preprocess(body, lang))
    toc = md.toc if "<li>" in md.toc else ""
    nav = []
    for n2, label, c2, indent in nav_items:
        cur = ' class="current"' if n2 == name else ""
        cls = ' sub' if indent else ""
        nav.append(f'<a href="{n2}.html"{cur} data-sub="{1 if indent else 0}" style="--c:{COLORS[c2]}" class="navlink{cls}">'
                   f'<span class="dot" style="background:{COLORS[c2]}"></span>{label}</a>')
        if n2 == name and toc:
            nav.append(f'<div class="toc">{toc}</div>')
    base = "../" if lang == "en" else ""
    other_lang = "fr" if lang == "en" else "en"
    other_href = f"../{name}.html" if lang == "en" else f"en/{name}.html"
    banner = "" if translated or lang == "fr" else f'<div class="callout missing"><p>{s["untranslated"]}</p></div>'
    page = TEMPLATE.format(lang=lang, title=html.escape(meta.get("title", name)), brand=s["brand"], base=base,
                           accent=COLORS.get(meta.get("color", color_default), COLORS["gris"]),
                           tag=s["tag"].format(k8s=k8s), other=s["other"], other_title=s["other_title"],
                           other_href=other_href, other_lang=other_lang, theme=s["theme"], nav="\n".join(nav),
                           banner=banner, content=content, footer=s["footer"], extra=extra)
    (out_dir / f"{name}.html").write_text(page, encoding="utf-8")


def build():
    if SITE.exists():
        shutil.rmtree(SITE)
    (SITE / "assets").mkdir(parents=True)
    for f in (DOCS / "assets").iterdir():
        shutil.copy(f, SITE / "assets")
    if quiz is not None:
        data = quiz.export()
        vf = CAPS / "quiz-verify.json"
        data["verified"] = json.loads(vf.read_text())["results"] if vf.exists() else {}
        (SITE / "assets" / "quiz.json").write_text(json.dumps(data, ensure_ascii=False), encoding="utf-8")
    k8s = re.search(r"K8S_VERSION=(\S+)", (ROOT / "versions.env").read_text()).group(1)
    total = 0
    for lang in LANGS:
        out_dir = SITE if lang == "fr" else SITE / "en"
        out_dir.mkdir(exist_ok=True)
        nav_items = []
        for name, label, color in NAV:
            if name == "quiz" and quiz is None:
                continue
            nav_items.append((name, label[lang], color, False))
            if name == "cours":
                for ch in course.CHAPTERS:
                    nav_items.append((f"cours-{ch['id']}", ch["title"][lang], ch["color"], True))
        pages = []
        for name, label, color in NAV:
            if name == "exercices":
                pages.append((name, gen_exercices(lang), color, True, ""))
            elif name == "examens-blancs":
                pages.append((name, gen_mocks(lang), color, True, ""))
            elif name == "cours":
                pages.append((name, gen_course_index(lang), color, True, ""))
                for ch in course.CHAPTERS:
                    pages.append((f"cours-{ch['id']}", gen_course_chapter(ch, lang), ch["color"], True, ""))
            elif name == "quiz":
                q = gen_quiz(lang)
                if q:
                    base = "../" if lang == "en" else ""
                    pages.append((name, q, color, True, f'\n<script src="{base}assets/quiz.js"></script>'))
            else:
                text, translated = page_source(name, lang)
                if text is None:
                    print(f"  (absent) {lang}/{name}.md")
                    continue
                pages.append((name, text, color, translated, ""))
        for name, text, color, translated, extra in pages:
            render(name, text, lang, color, k8s, nav_items, out_dir, translated, extra)
            total += 1
    print(f"site/ : {total} pages ({', '.join(LANGS)})")


if __name__ == "__main__":
    build()
