def course_status():
    f = CAPS / "course" / "verify.json"
    return json.loads(f.read_text()) if f.exists() else {"results": {}, "kubernetes": "?"}


def gen_course_index(lang):
    s, fr = S[lang], lang == "fr"
    t_ = "Cours complet CKAD" if fr else "Full CKAD course"
    parts = [f"---\ntitle: {t_}\ncolor: gris\n---\n# {t_}\n\n{s['course_intro']}\n"]
    st = course_status()
    for ch in course.CHAPTERS:
        parts.append(f"\n## [{ch['title'][lang]}](cours-{ch['id']}.html)\n\n{ch['intro'][lang]}\n")
        for c in ch["concepts"]:
            v = st["results"].get(c["id"], "")
            mark = {"PASS": " ✔", "SKIP": " ·", "ILLUSTRATIF": ""}.get(v, "")
            parts.append(f"- [{c['title'][lang]}](cours-{ch['id']}.html#{c['id']}){mark}")
    parts.append("\n" + ("✔ = commandes exécutées avec succès lors de la dernière vérification ; · = non exécutables ici "
                         "(capacité absente)." if fr else
                         "✔ = commands executed successfully during the last verification; · = not executable here "
                         "(missing capability)."))
    return "\n".join(parts)


def gen_course_chapter(ch, lang):
    s = S[lang]
    st = course_status()
    k8s = st.get("kubernetes", "?")
    parts = [f"---\ntitle: {ch['title'][lang]}\ncolor: {ch['color']}\n---\n# {ch['title'][lang]}\n\n{ch['intro'][lang]}\n"]
    for c in ch["concepts"]:
        parts.append(f"\n## {c['title'][lang]} {{#{c['id']}}}\n\n{c['text'][lang]}\n")
        verdict = st["results"].get(c["id"])
        req = {"metrics": "metrics-server", "netpol": "NetworkPolicy"}.get(c.get("requires"), c.get("requires"))
        if c["run"] is None:
            badge = s["run_illus"]
        elif verdict == "PASS":
            badge = s["run_ok"].format(k8s=k8s)
        elif verdict == "SKIP":
            badge = s["run_skip"].format(req=req)
        else:
            badge = s["run_unverified"]
        if c["cmd"]:
            parts.append(f'<p class="badge">{badge}</p>\n\n```bash\n{textwrap.dedent(c["cmd"]).strip()}\n```\n')
        out = CAPS / "course" / f"{c['id']}.txt"
        if out.exists() and out.read_text().strip():
            body = colorize(html.escape(out.read_text().rstrip()))
            parts.append(f'<details class="out"><summary>{s["out"]}</summary>\n<pre class="terminal"><code>{body}</code></pre>\n</details>\n')
        if c.get("yaml"):
            parts.append(f'<p class="badge">{s["yaml_ok"]}</p>\n\n```yaml\n{textwrap.dedent(c["yaml"]).strip()}\n```\n')
        if c.get("trap"):
            parts.append(f":::piege\n{c['trap'][lang]}\n:::\n")
        if c.get("exam"):
            parts.append(f":::examen\n{c['exam'][lang]}\n:::\n")
    return "\n".join(parts)


