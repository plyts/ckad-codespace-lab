def gen_mocks(lang):
    fr = lang == "fr"
    t_ = "Examens blancs corrigés" if fr else "Mock exams with answers"
    parts = [f"---\ntitle: {t_}\ncolor: gris\n---\n# {t_}\n",
             (":::examen\nFais d'abord l'examen dans le labo (`mock start N`, puis `mock grade N` à la sonnerie). "
              "N'ouvre les corrections qu'ensuite : elles sont repliées.\n:::\n") if fr else
             (":::examen\nTake the exam in the lab first (`mock start N`, then `mock grade N` when time is up). "
              "Only then open the answers: they are collapsed.\n:::\n")]
    for d in sorted((ROOT / "mock-exams").glob("mock-*")):
        n = d.name.split("-")[1]
        meta, intro = EX.mock_meta(n)
        if lang == "en" and (d / "exam.en.md").exists():
            meta, intro = front((d / "exam.en.md").read_text(encoding="utf-8"))
            intro = intro.strip()
        tasks = EX.mock_tasks(n)
        parts.append(f"\n## {'Examen blanc' if fr else 'Mock exam'} {n} — {meta.get('title')} "
                     f"({meta.get('duration')} min, {len(tasks)} {'tâches' if fr else 'tasks'})\n\n{intro}\n")
        parts.append(("| # | Poids | Domaine | Contexte | Tâche |" if fr else "| # | Weight | Domain | Context | Task |")
                     + "\n|---|---|---|---|---|")
        for i, t in enumerate(tasks, 1):
            parts.append(f"| {i} | {t.weight} % | {t.domain} | `{t.ctx}` | {unit_text(t, lang)[0]} |")
        for i, t in enumerate(tasks, 1):
            title, body = unit_text(t, lang)
            parts.append(f"\n### {'Tâche' if fr else 'Task'} {i} — {title} ({t.weight} %)\n\n*"
                         f"{'contexte' if fr else 'context'} `{t.ctx}` · namespace `{t.ns}` · {t.time} min · [doc]({t.doc})*\n\n"
                         f"{body}\n\n<details><summary>{'Correction commentée' if fr else 'Commented answer'}</summary>\n\n"
                         f"```bash\n{solution_text(t, lang)}\n```\n\n</details>\n")
    return "\n".join(parts)


